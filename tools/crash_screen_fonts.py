#!/usr/bin/env python3
"""Bake the crash screen's ASCII fonts into packed 1-bit masks.

Normal Zig builds use the checked-in assets and do not require Python/Pillow.
Regenerate from the core root with:
    python3 tools/crash_screen_fonts.py --font-dir /usr/share/fonts/Adwaita
"""

import argparse
from pathlib import Path

from PIL import Image, ImageFont


FONTS = (
    ("ui", "AdwaitaSans-Regular.ttf", 13, 800),
    ("brand", "AdwaitaSans-Regular.ttf", 13, 850),
    ("title", "AdwaitaSans-Regular.ttf", 15, 850),
    ("data", "AdwaitaSans-Regular.ttf", 14, 800),
    ("small", "AdwaitaSans-Regular.ttf", 11, 800),
    ("bytes", "AdwaitaMono-Bold.ttf", 11, None),
)


def bake_glyph(font, char, bitmap, embolden=True):
    # Threshold the grayscale master for proportional glyphs. Its baseline
    # avoids the monochrome hinter's raised 'r' at these small pixel sizes.
    mode = "L" if embolden else "1"
    raster, (left, top) = font.getmask2(char, mode=mode, anchor="ls")
    source_width, height = raster.size
    # One additional horizontal ink column gives vertical stems enough weight
    # on a 4:3 TV. Bake it once; do not scale glyphs or expand strokes at runtime.
    width = source_width + int(embolden and height != 0)
    mask = Image.new("1", (max(width, 1), max(height, 1)))
    for y in range(height):
        for x in range(width):
            mask.putpixel((x, y), any(
                raster[y * source_width + sx] >= 128
                for sx in ((x, x - 1) if embolden else (x,))
                if 0 <= sx < source_width
            ))
    advance = round(font.getlength(char) * 64)
    if embolden:
        bounds = mask.getbbox()
        if bounds is None:
            width, height = 0, 0
            left, top = 0, 0
            advance = (round(font.getlength(char)) + 1) * 64
        else:
            mask = mask.crop(bounds)
            width, height = mask.size
            left, top = 0, top + bounds[1]
            # Use the baked ink width, not an unhinted outline advance plus
            # tracking. Every proportional glyph has one clear pixel after it.
            advance = (width + 1) * 64
    offset = len(bitmap)
    bits = [mask.getpixel((x, y)) != 0 for y in range(height) for x in range(width)]
    for start in range(0, len(bits), 8):
        byte = 0
        for index, bit in enumerate(bits[start:start + 8]):
            byte |= int(bit) << (7 - index)
        bitmap.append(byte)
    return offset, width, height, left, top, advance


def generate(font_dir, output):
    bitmap = bytearray()
    lines = [
        "// Generated by tools/crash_screen_fonts.py; do not edit glyph metadata.",
        "// Adwaita fonts: see LICENSE.txt. Masks are row-major, MSB first, 1 bpp.",
        "pub const Glyph = struct {",
        "    offset: u16,",
        "    width: u8,",
        "    height: u8,",
        "    bearing_x: i8,",
        "    bearing_y: i8,",
        "    advance_64: u16,",
        "};",
        "pub const Font = struct { glyphs: []const Glyph };",
        'pub const bitmap = @embedFile("glyphs.bin");',
    ]
    for name, filename, size, weight in FONTS:
        font = ImageFont.truetype(str(font_dir / filename), size)
        # Native-height proportional glyphs: no aspect compensation or runtime
        # stroke expansion. Use the variable font's heavier master directly.
        if weight is not None:
            font.set_variation_by_axes([
                weight if axis["name"] == b"Weight" else axis["default"]
                for axis in font.get_variation_axes()
            ])
        lines.extend((f"pub const {name}: Font = .{{", "    .glyphs = &.{"))
        for code in range(32, 127):
            values = bake_glyph(font, chr(code), bitmap, embolden=name != "bytes")
            fields = ("offset", "width", "height", "bearing_x", "bearing_y", "advance_64")
            initializer = ", ".join(f".{field} = {value}" for field, value in zip(fields, values))
            lines.append("        .{ " + initializer + " }, // ASCII " + str(code))
        lines.extend(("    },", "};"))
    lines.extend(("// Compatibility name; diagnostic text is now proportional.",
                  "pub const mono = data;"))
    output.mkdir(parents=True, exist_ok=True)
    (output / "fonts.zig").write_text("\n".join(lines) + "\n")
    (output / "glyphs.bin").write_bytes(bitmap)
    print(f"Baked {len(FONTS)} ASCII fonts: {len(bitmap)} bytes of 1-bit glyph masks")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/fonts/Adwaita"))
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/n64/debug/crash_screen")
    args = parser.parse_args()
    generate(args.font_dir, args.output)
