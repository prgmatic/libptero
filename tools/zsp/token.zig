pub const Tag = enum {
    eof,
    ident,
    string,
    number,
    register,
    at,
    colon,
    comma,
    equal,
    equal_equal,
    not_equal,
    plus,
    plus_equal,
    minus,
    minus_equal,
    star,
    star_equal,
    slash,
    slash_equal,
    ampersand,
    ampersand_equal,
    pipe,
    pipe_equal,
    caret,
    caret_equal,
    tilde,
    nor,
    nor_equal,
    less,
    less_equal,
    shift_left,
    shift_left_equal,
    greater,
    greater_equal,
    shift_right,
    shift_right_equal,
    logical_shift_right,
    logical_shift_right_equal,
    type_start,
    type_end,
    l_paren,
    r_paren,
    l_brace,
    r_brace,
    semicolon,
};

pub const Token = struct {
    tag: Tag,
    text: []const u8,
    line: usize,
    column: usize,
};
